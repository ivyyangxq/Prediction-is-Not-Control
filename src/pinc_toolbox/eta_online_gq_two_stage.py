"""Learned-eta qualification for the existing predictable SimpleGQ route.

The same nearest-record domain is used by eta_domain's native query adapter.
It qualifies current rows without changing the full planned denominator N.
"""
from copy import deepcopy
import numpy as np
from .two_stage_report import run_two_stage_report
from .certified_source_workflow_backend import CertifiedSourceEvaluator
from .predictable_gq_two_stage import prepare_predictable_gq_region, run_predictable_gq_two_stage


def _qualified_block(block, domain):
    from .eta_domain import domain_mask
    states=np.asarray(block['states'],float)
    actions=np.asarray(block['actions'],float)
    if states.ndim!=2 or states.shape[1]!=2 or len(states)!=len(actions):
        raise ValueError('source states must be [physical_state, previous_action]')
    n=len(actions)
    planned=block.get('intended_n',n)
    if isinstance(planned,bool) or not isinstance(planned,int) or planned<1:
        raise ValueError('intended_n must be a positive predeclared integer')
    if n!=planned:
        raise ValueError('incomplete_fixed_window: observed rows differ from intended_n')
    result=domain_mask(domain,np.column_stack((states,actions)).tolist())
    if result.get('status')!='ready' or any(v is None for v in result.get('mask',[])):
        raise ValueError('eta_domain_evaluation_unavailable: '+str(result.get('reason')))
    mask=np.asarray(result['mask'],bool)
    if mask.shape!=(n,):raise ValueError('eta mask dimension mismatch')
    weights=np.asarray(block['weights'],float)
    if weights.ndim!=2 or weights.shape[1]!=n or not np.isfinite(weights).all() or np.any(weights<0) or np.any(weights>1):
        raise ValueError('weights must be predictable m by N values in [0,1]')
    qualified=deepcopy(block)
    qualified['weights']=(weights*mask[None,:]).tolist()
    support={'planned_rows':planned,'observed_rows':n,'qualified_rows':int(mask.sum()),
             'unsupported_rows':int((~mask).sum()),'fixed_denominator':n,
             'mask':mask.tolist(),'point_coordinates':['physical_state','previous_action','action'],
             'informative_weight_rows':int(np.count_nonzero(np.any(weights*mask[None,:]!=0,axis=0))),
             'domain_result':result}
    return qualified,support


def run_eta_online_gq_two_stage(*, domain, detection_reference, detection_windows,
                               source_reference, source_window, sigma, source_deadline,
                               alpha_detection_reference=.005, alpha_detection_noise=.005,
                               alpha_source_reference=.025, alpha_source_noise=.025,
                               latent_bound=.6, model_bound=2., assumptions=None):
    """Finite detector calendar and one source window on a frozen learned domain.

    Source reference is not selected or refitted by the eta selector. Selection
    data must be separate from all diagnostic blocks. Native behavior actions
    should be generated by eta_domain.eta_qualified_native_action when native
    query qualification is desired; this runner does not manufacture a policy.
    """
    context={'route':'eta_qualified_online_simple_gq','source_deadline':source_deadline,
             'eta_domain':deepcopy(domain),'eta_Q_continuation':'not_qualified_by_this_adapter'}
    if not isinstance(domain,dict) or domain.get('status')!='ready':
        r=run_two_stage_report({'status':'unavailable','reason':'eta_initialization_unavailable'},context=context)
        r['completion']['failures'].append({'reason':'eta_initialization_unavailable'})
        return r
    if not isinstance(detection_windows,list) or not detection_windows:
        raise ValueError('finite predeclared detection windows required')
    selection_ids=domain.get('selection_record_ids')
    if not isinstance(selection_ids,list) or not selection_ids:
        raise ValueError('eta domain requires selection_record_ids')
    blocks=[detection_reference,source_reference,source_window]+detection_windows
    if set(selection_ids)&{i for b in blocks for i in b['record_ids']}:
        raise ValueError('eta selection panel overlaps diagnostic data')
    times=[max(w['dates']) for w in detection_windows]
    if any(t>=u for t,u in zip(times,times[1:])):
        raise ValueError('detection endpoints must be strictly increasing')
    cutoff=domain.get('as_of')
    if cutoff is None or cutoff>=min(min(w['dates']) for w in detection_windows):
        raise ValueError('eta initialization must precede all detection observations')
    detector_ids=[i for w in detection_windows for i in w['record_ids']]
    old_ids=detection_reference['record_ids']
    if set(source_reference['record_ids'])&(set(old_ids)|set(detector_ids)):
        raise ValueError('source reference overlaps detection data')
    if set(old_ids)&set(detector_ids) or max(detection_reference['dates'])>=min(min(w['dates']) for w in detection_windows):
        raise ValueError('detector reference must be separate old observations')
    records=[];failures=[];alarm_time=None
    for time,window in zip(times,detection_windows):
        try:
            qualified,support=_qualified_block(window,domain)
            if not support['informative_weight_rows']:
                raise ValueError('no_eta_qualified_weighted_detection_rows')
            measured=prepare_predictable_gq_region(detection_reference,qualified,sigma=sigma,
                alpha_reference=alpha_detection_reference,alpha_noise=alpha_detection_noise,
                calendar_size=len(times),latent_bound=latent_bound,model_bound=model_bound)
            c0=CertifiedSourceEvaluator(measured['source_spec'])('C0')
            status={'excluded':'alarm','compatible':'no_alarm'}.get(c0['status'],'unresolved')
            records.append({'time':time,'status':status,'measurement':measured,'eta_support':support,'C0':c0})
            if status=='unresolved':failures.append({'time':time,'reason':'detector_unresolved'})
            if status=='alarm':alarm_time=time;break
        except Exception as exc:
            item={'time':time,'status':'unavailable','reason':str(exc)}
            # Domain-support counts remain visible even for an empty opportunity.
            try:item['eta_support']=_qualified_block(window,domain)[1]
            except Exception:
                item['eta_support']={'planned_rows':window.get('intended_n',len(window.get('actions',[]))),
                    'observed_rows':len(window.get('actions',[])),'qualified_rows':None,'status':'unavailable'}
            records.append(item);failures.append({'time':time,'reason':str(exc)})
    stage1={'status':'alarm' if alarm_time is not None else 'unavailable' if failures else 'no_alarm',
            'alarm_time':alarm_time,'first_alarm':alarm_time,'calendar':times,
            'event':'first C0 exclusion using W_eta=W*q and fixed full N',
            'records':records,'not_visited_times':times[len(records):],
            'provenance':{'record_ids':detector_ids+selection_ids,'detector_reference_ids':old_ids}}
    support_source=None
    if alarm_time is None:
        report=run_two_stage_report(stage1,context=context)
    else:
        try:
            qualified,support_source=_qualified_block(source_window,domain)
            if not support_source['informative_weight_rows']:
                raise ValueError('no_eta_qualified_weighted_source_rows')
            report=run_predictable_gq_two_stage(stage1=stage1,reference=source_reference,future=qualified,
                sigma=sigma,source_deadline=source_deadline,alpha_reference=alpha_source_reference,
                alpha_noise=alpha_source_noise,calendar_size=1,latent_bound=latent_bound,
                model_bound=model_bound,assumptions=assumptions)
            report['context'].update(context)
        except Exception as exc:
            if support_source is None:
                support_source={'planned_rows':source_window.get('intended_n',len(source_window.get('actions',[]))),
                    'observed_rows':len(source_window.get('actions',[])),'qualified_rows':None,'status':'unavailable','reason':str(exc)}
            report=run_two_stage_report(stage1,context=context,
                readiness={'status':'unavailable','reason':str(exc)})
    report['eta_support']={'source':support_source,'selection_record_ids':selection_ids,
        'qualification':'same nearest-record scaled-Linf domain as native query adapter',
        'normalization':'all planned rows N; no supported-row renormalization',
        'eta_selection_guarantee':'separate from source conditional error bound'}
    report['completion']['failures']=failures+report['completion']['failures']
    report['errors']['detection']['type_i']['target_budget']=alpha_detection_reference+alpha_detection_noise
    if (assumptions or {}).get('detector_predictable_region_assumptions') is True:
        report['errors']['detection']['type_i'].update(proved_bound=alpha_detection_reference+alpha_detection_noise,
            status='theorem_under_declared_assumptions')
    db=report['errors']['detection']['type_i']['proved_bound']
    sb=report['errors'].get('source_joint',{}).get('type_i',{}).get('proved_bound')
    report['errors']['joint']['type_i']['target_budget']=alpha_detection_reference+alpha_detection_noise+alpha_source_reference+alpha_source_noise
    if db is not None and sb is not None:
        report['errors']['joint']['type_i'].update(proved_bound=min(1.,db+sb),status='theorem_under_declared_assumptions')
    return report
