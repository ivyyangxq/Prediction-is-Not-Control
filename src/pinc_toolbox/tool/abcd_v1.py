MODES=('public_proxy_freeze','evaluator_latent_freeze')
EXPECTED=('main','fixed_action','fixed_public_environment','both_fixed')


class ControlledFork:
    """Four branch-specific private host clones; latent truth stays in host."""
    def __init__(self,env,raw,mode,module,reward_spec):
        if tuple(BRANCHES)!=EXPECTED:raise RuntimeError('registered executor branch order changed')
        if mode not in MODES:raise ValueError('unknown intervention mode')
        self.env=env;self.raw=raw;self.mode=mode;self.module=module
        self.reward_spec=deepcopy(reward_spec)
        self.reward_equation=RewardEquation(reward_spec['expression'],reward_spec['inputs'],reward_spec['parameters'])
        self.public_input_names=('w',) if mode=='public_proxy_freeze' else ('evaluator_intervention_selector',)
        self.clone_index=0;self.branch=None;self.fork=int(env._next_t)
        self.fork_w=float(env.w[0,self.fork]);self.fork_latent=env.latent[0,self.fork].copy()

    def __deepcopy__(self,memo):
        # The existing executor clones in the explicitly checked BRANCHES order.
        index=self.clone_index;self.clone_index+=1
        if index>=4:raise RuntimeError('unexpected extra environment clone')
        out=object.__new__(type(self));memo[id(self)]=out
        out.env=deepcopy(self.env,memo);out.env.w=out.env.proxy_all[:,:,0]
        out.raw=self.raw;out.mode=self.mode;out.module=self.module
        out.reward_spec=deepcopy(self.reward_spec);out.reward_equation=self.reward_equation
        out.public_input_names=self.public_input_names;out.clone_index=0
        out.branch=EXPECTED[index];out.fork=self.fork;out.fork_w=self.fork_w
        out.fork_latent=self.fork_latent.copy()
        return out

    def _holds(self):return self.branch in ('fixed_public_environment','both_fixed')

    def _hold_latent_at(self,time):
        if self.mode=='evaluator_latent_freeze' and self._holds():
            self.env.latent[0,time]=self.fork_latent
            loading=self.module._PARENT.PROXY_LOADING
            self.env.proxy_all[0,time]=self.fork_latent@loading.T+self.env.measurement_noise[0,time]

    def public_input(self,time):
        self._hold_latent_at(time)
        value=float(self.env.w[0,time]) if self.mode=='public_proxy_freeze' else 0.
        return PublicInput(np.array([value]),int(time))

    def condition(self,state,public):
        time=int(self.env._next_t);self._hold_latent_at(time)
        if abs(float(state.physical[0])-self.env.state[0,time])>1e-11:
            raise ValueError('branch enterprise state no longer matches its own private host')
        if abs(float(state.physical[2])-self.env.action[0,time-1])>1e-12:
            raise ValueError('branch anchor is not its previous executed action')
        # In latent mode the selector carries no economic information. Actual
        # public proxy is generated by the held private latent plus fresh noise.
        state.physical[1]=public.values[0] if self.mode=='public_proxy_freeze' else self.env.w[0,time]
        return state

    def step(self,time,state,action,public):
        if time!=self.env._next_t:raise ValueError('host clock mismatch')
        self._hold_latent_at(time)
        rows=self.raw.loc[self.raw.period==time].sort_values('path_id')
        actions=rows.action.to_numpy(float).copy()
        if len(actions)!=self.env.paths:raise ValueError('external companion action tape missing')
        actions[0]=action
        x=float(self.env.state[0,time]);self.env.step(time,actions)
        self._hold_latent_at(time+1)
        next_w=(self.fork_w if self._holds() else float(self.env.w[0,time+1])) if self.mode=='public_proxy_freeze' else float(self.env.w[0,time+1])
        physical={'state':x,'w':float(state.physical[1]),'previous_action':float(state.physical[2]),'action':float(action)}
        reward=float(self.reward_equation({alias:physical[role] for alias,role in self.reward_spec['inputs'].items()}))
        return PublicOutcome(np.array([self.env.state[0,time+1],next_w,action]),float(reward),time+1)


def run_abcd(root,session,*,seed,family,fork=40,steps=4,mode='public_proxy_freeze',raw_history=None):
    root=Path(root)
    reward_spec=deepcopy(session.settings['reward'])
    if not set(reward_spec['inputs'].values())<=set(('state','w','previous_action','action')):
        raise ValueError('controlled ABCD adapter requires provided physical inputs or the declared same-meaning action interface')
    if session.settings['path']!=0:raise ValueError('controlled fork currently targets original RND2 path0')
    if not np.array_equal(session.grid,np.linspace(0.,.1,11)) or not session.feasible.all():
        raise ValueError('this registered ABCD executor requires its original eleven-action grid with all actions publicly feasible; it cannot silently replace a custom action interface')
    settings=session.settings
    history=session.history.copy() if raw_history is None else raw_history.copy()
    if set(history.path_id.unique())!=set(range(32)):raise ValueError('controlled host requires the complete32-unit public prefix')
    if fork<32 or fork+steps>int(history.period.max())+1:raise ValueError('choose a fork>=32 with enough externally logged companion dates')
    if mode not in MODES:raise ValueError('choose public_proxy_freeze or evaluator_latent_freeze')
    original=_load('abcd_extension_original_host',root/'DGP/RND/02_state_dependent_local/model_source_v004/environment.py')
    round_module=_load('abcd_extension_round_host',root/'experiments/round_coefficient_precision128_20261110/run_round.py')
    dgp=round_module.round_environment(original)
    source={'N':'STABLE','CL_Q100':'LATENT_F','CM':'MODEL_A','MIX':'MODEL_LATENT'}[family]
    env=dgp.Environment(int(seed),source,paths=32,horizon=64,switch_date=32)
    if family=='CL_Q100':env.g_profile[:]/=.69375;env.g_t=env.g_profile
    _extend_original_host(env,dgp,max(63,int(history.period.max())))
    for date in range(fork):
        rows=history.loc[history.period==date].sort_values('path_id')
        if len(rows)!=32 or not np.isfinite(rows[['state','w','action','next_state','next_w']].to_numpy()).all():
            raise ValueError('complete observed prefix required; missing actions cannot be fabricated')
        np.testing.assert_allclose(env.state[:,date],rows.state.to_numpy(),rtol=0,atol=1e-12)
        np.testing.assert_allclose(env.w[:,date],rows.w.to_numpy(),rtol=0,atol=1e-12)
        env.step(date,rows.action.to_numpy())
        np.testing.assert_allclose(env.state[:,date+1],rows.next_state.to_numpy(),rtol=0,atol=1e-12)
        np.testing.assert_allclose(env.w[:,date+1],rows.next_w.to_numpy(),rtol=0,atol=1e-12)
    visible=history.loc[history.release_period<=fork].drop(columns=['reward'],errors='ignore')
    request={'history':visible.to_dict('records'),'learner':{
        'as_of':int(fork),'warmup_as_of':settings.get('warmup_as_of',8),'window':settings['window'],'path_id':0,'refit_every':1,
        'beta':settings['discount'],'horizon':settings['horizon'],'nodes_per_memory':settings.get('nodes_per_memory',5),'noise_nodes':settings.get('noise_nodes',4),
        'q_evaluation':'bellman','query_horizon':settings['horizon'],
        'reward_equation':deepcopy(reward_spec),'reward_inputs':deepcopy(reward_spec['inputs'])},'steps':int(steps),
        'stage1':{'status':'unavailable','reason':'ABCD payoff diagnostic is not a detector or source test'},
        'context':{'route':'GQTool controlled ABCD adapter','intervention':mode},
        'evaluator_configuration':{'seed':int(seed),'family':family,'fork':int(fork),'steps':int(steps),'intervention':mode,
            'scope':'private evaluator host configuration, never passed to the learner constructor'}}
    before=None if session.evidence is None else digest(session.evidence.snapshot())
    repair=deepcopy(session.repair)
    # JSON stores the user's exact form and parameters. This extension bridge
    # constructs the existing native callable without changing that target.
    execution_request=deepcopy(request)
    execution_request['learner']['reward_equation']=RewardEquation(reward_spec['expression'],reward_spec['inputs'],reward_spec['parameters'])
    report=run_request(execution_request,ControlledFork(env,history,mode,dgp,reward_spec))
    after=None if session.evidence is None else digest(session.evidence.snapshot())
    if before!=after or session.repair!=repair:raise AssertionError('ABCD must not alter source or repair state')
    report['extension']={'version':'abcd_product_v2_prescribed_reward','intervention':mode,
        'prescribed_reward':reward_spec,'reward_digest':digest(reward_spec),
        'request_bridge':'ABCD extension converts serialized reward specification to the existing native RewardEquation callable; no reward fitting',
        'scope':'controlled known-host private evaluator fork; not ordinary-panel causal identification',
        'A':'main action with natural latent and public proxy',
        'B':'fixed first A action with natural latent and public proxy',
        'C':'replay current A action, public proxy frozen' if mode=='public_proxy_freeze' else 'replay current A action, evaluator true latent held at fork; proxy regenerated with dated measurement noise',
        'D':'both action and proxy fixed' if mode=='public_proxy_freeze' else 'fixed first A action and evaluator true latent held at fork; proxy regenerated',
        'latent_in_learner_inputs':False,'unchanged_source_digest':before,'unchanged_repair':repair,
        'qualification':'existing executor support checks, own released histories and native full RA-GQ; no unsupported forced action or fallback',
        'proxy_scope':'proxy hold does not hold latent. With identical actions and matched latent/noise, physical state paths coincide; the user reward may still directly depend on the held public input.',
        'latent_mode_bridge':'existing synchronous action scheduling and qualification reused; host executes private C/D latent interventions; public selector contains no latent values' if mode=='evaluator_latent_freeze' else None,
        'not_source_evidence':True,'formal_batch_effect':'none; separately versioned engineering/product feature'}
    return request,report


def export_abcd(directory,request,report):
    directory=Path(directory);directory.mkdir(parents=True,exist_ok=False)
    (directory/'ABCD_REQUEST.json').write_text(json.dumps(request,indent=2,allow_nan=False)+'\n')
    (directory/'ABCD_REPORT.json').write_text(json.dumps(report,indent=2,allow_nan=False)+'\n')
    result=report['counterfactual'];comparison=result['comparison'];lines=['# Actual ABCD execution','',
        'Intervention: '+report['extension']['intervention'],'',
        '| Path | Status | Completed steps | Discounted return |','|---|---|---:|---:|']
    for letter,key in zip('ABCD',EXPECTED):
        branch=result['branches'][key];lines.append(f"| {letter} | {branch['status']} | {branch['completed_steps']} | {branch['discounted_return']} |")
    lines+=['','Comparison: '+comparison['status'],'','```json',json.dumps(comparison['signed_differences'],indent=2),'```','',
        'These are matched finite-path realized discounted returns, not regret or source identification. Support exits are retained, with unavailable full comparisons. '+report['extension']['scope']]
    (directory/'ABCD_REPORT.md').write_text('\n'.join(lines)+'\n')
    return directory


def install_abcd(ui,root):
    """Add real menu controls to an existing GQTool instance, no frozen edits."""
    w=ui.w;root=Path(root)
    mode=w.Dropdown(options=[('Hold public proxy (latent continues)','public_proxy_freeze'),('Evaluator-only latent hold','evaluator_latent_freeze')],description='ABCD intervention',layout=w.Layout(width='95%'))
    seed=w.IntText(value=4239010022,description='Known host seed')
    family=w.Dropdown(options=['N','CL_Q100','CM','MIX'],value='CM',description='Known evaluator law')
    fork=w.IntText(value=40,description='Common fork period');steps=w.IntSlider(value=4,min=1,max=12,description='Executed path periods')
    target=w.Text(description='New ABCD directory',layout=w.Layout(width='95%'))
    button=w.Button(description='Execute all four ABCD paths',button_style='warning')
    state={'last_report':None,'last_request':None}
    def run(_):
        def operation():
            if ui.session is None:raise ValueError('First import and configure the RND2 panel/proxy in this workbench')
            request,report=run_abcd(root,ui.session,seed=seed.value,family=family.value,fork=fork.value,steps=steps.value,mode=mode.value)
            directory=export_abcd(Path(target.value).expanduser(),request,report)
            state.update(last_report=report,last_request=request,directory=str(directory))
            result=report['counterfactual'];print(json.dumps({'status':result['status'],'intervention':mode.value,'comparison':result['comparison'],'directory':str(directory)},ensure_ascii=False,indent=2))
        ui._safe(operation)
    button.on_click(run)
    panel=w.VBox([w.HTML('<b>Four executed ABCD paths</b>: requires a declared controlled RND2 evaluator fork. Ordinary panel/W data alone do not identify unexecuted returns. Public and latent interventions are labeled separately. Results do not authorize MODEL or repair; support refusals remain refusals.'),mode,seed,family,fork,steps,target,button])
    ui.root.children=(*ui.root.children[:-1],panel,ui.output)
    return {'mode':mode,'seed':seed,'family':family,'fork':fork,'steps':steps,'target':target,'button':button,'state':state,'panel':panel}
