"""Isolated product extension v1: actual registered four-path execution.

This file is outside the in-flight confirmation's frozen runtime. It reuses
counterfactual_cli.run_request, preserves support refusals, and never changes a
PanelSession source/repair state. Controlled RND2 host credentials are explicit
prerequisites, not an inference from observational CSVs.
"""
from __future__ import annotations
